# მონაცემების შეყვანა
a = float(input("შეიყვანეთ I რიცხვი: "))
op = input("შეიყვანეთ ოპერატორი (+, -, *, /): ")
b = float(input("შეიყვანეთ II რიცხვი: "))

# გამოთვლა
if op == "+":
    print(f"შედეგი: {a + b}")
elif op == "-":
    print(f"შედეგი: {a - b}")
elif op == "*":
    print(f"შედეგი: {a * b}")
elif op == "/":
    print(f"შედეგი: {a / b}" if b != 0 else "ნულზე გაყოფა არ შეიძლება!")
else:
    print("არასწორი ოპერატორი!")
