# 3 რიცხვის შეყვანა
a = float(input("შეიყვანეთ I რიცხვი: "))
b = float(input("შეიყვანეთ II რიცხვი: "))
c = float(input("შეიყვანეთ III რიცხვი: "))

# შემოწმება და მაქსიმუმის პოვნა
if a == b or b == c or a == c:
    print("გთხოვთ შეიყვანოთ განსხვავებული რიცხვები!")
else:
    print(f"უდიდესი რიცხვია: {max(a, b, c)}")
